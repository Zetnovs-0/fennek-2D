const ENDING_ORDER = [
  'warm_uni', 'lonely_uni', 'second_try', 'fennec_college',
  'quiet_room', 'wrong_college', 'own_path',
];

const MOM_PLAN = 'на юридический факультет Университета права и экономики';

function dreamOf(state) {
  return DREAMS[state.dreamKey] || DREAMS.arch;
}

function resolveEnding(state, kind) {
  const { study, courage, family } = state.stats;
  if (kind === 'take') {
    if (study >= 6 && courage >= 3) {
      return family >= 4 || state.flags.confessed ? 'warm_uni' : 'lonely_uni';
    }
    if (study >= 4) return 'second_try';
    return 'fennec_college';
  }
  if (state.flags.finalChoice === 'mom') return 'quiet_room';
  if (state.flags.finalChoice === 'own' && courage >= 4 && study >= 4) return 'own_path';
  if (state.flags.finalChoice === 'gap' && courage >= 5 && study >= 3) return 'own_path';
  return 'wrong_college';
}

function formatText(input, state) {
  let text = typeof input === 'function' ? input(state) : input;
  if (text == null) return '';
  const dream = dreamOf(state);
  text = String(text);
  text = text.replace(/\{g:([^}|]+)\|([^}]+)\}/g, (_, m, f) => (state.gender === 'f' ? f : m));
  const tokens = {
    name: state.name || 'Ты',
    fennec: state.fennecName || (state.flags.leftFennec ? 'Рыжик' : 'фенёк'),
    Fennec: state.fennecName || (state.flags.leftFennec ? 'Рыжик' : 'Фенёк'),
    uni: dream.uni,
    faculty: dream.faculty,
    dreamLabel: dream.label,
    dreamLower: dream.lower,
    dreamDesc: dream.desc,
    dreamAbout: dream.about,
    dreamWhere: dream.where,
    examMotto: dream.examMotto,
    collegeProgram: dream.collegeProgram,
    collegeSmell: dream.collegeSmell,
    momPlan: MOM_PLAN,
    brother: 'Дима',
    sister: 'Мила',
  };
  text = text.replace(/\{(\w+)\}/g, (m, key) => (tokens[key] !== undefined ? tokens[key] : m));
  return text;
}

function lineView(line, state) {
  return {
    who: line.who || '',
    tone: line.tone || 'narrator',
    text: formatText(line.text, state),
  };
}

function choiceView(choice, state) {
  return {
    text: formatText(choice.text, state),
    sub: choice.sub ? formatText(choice.sub, state) : '',
    effects: choice.effects || {},
  };
}

function endingView(id, state) {
  const e = ENDINGS[id];
  if (!e) return null;
  return {
    id,
    title: e.title,
    tag: formatText(e.tag, state),
    mood: e.mood,
    body: e.body.map((p) => formatText(p, state)),
  };
}

function hotspotView(id, state) {
  const h = HOTSPOTS[id];
  if (!h) return null;
  return {
    id,
    label: formatText(h.label, state),
    title: formatText(h.title, state),
    lines: h.lines.map((l) => formatText(l, state)),
    effects: h.effects || {},
  };
}

function checkState(state) {
  const nodeIds = Object.keys(NODES);
  const errors = [];
  const referenced = new Set();
  for (const [id, node] of Object.entries(NODES)) {
    const targets = [];
    if (node.choices) targets.push(...node.choices.map((c) => c.next));
    if (node.next) targets.push(node.next);
    for (const t of targets) {
      referenced.add(t);
      if (!NODES[t]) errors.push(`${id}: неизвестная нода «${t}»`);
    }
    if (!node.type && !node.choices && !node.next) errors.push(`${id}: нет выхода`);
    if (node.type === 'ending' && !node.resolve) errors.push(`${id}: нет resolve`);
  }
  for (const id of nodeIds) {
    if (id !== STORY_START && !referenced.has(id)) errors.push(`${id}: недостижима`);
  }
  return errors;
}

